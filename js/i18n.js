(function () {
  const q = new URLSearchParams(location.search).get("lang");
  let saved = null;
  try { saved = localStorage.getItem("lang"); } catch (e) {}
  window.LANG = q === "en" || q === "ru" ? q : saved === "en" || saved === "ru" ? saved : "ru";
  const listeners = [];
  window.t = (k) => (I18N[LANG] && I18N[LANG][k]) || I18N.ru[k] || k;
  window.L = (o) => (o && typeof o === "object" ? o[LANG] ?? o.ru : o);
  window.onLang = (fn) => { listeners.push(fn); fn(); };
  window.applyLang = () => {
    document.documentElement.lang = LANG;
    document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => { el.alt = t(el.dataset.i18nAlt); });
    const tt = document.querySelector("title[data-ru]");
    if (tt) document.title = LANG === "en" ? tt.dataset.en : tt.dataset.ru;
    listeners.forEach((fn) => fn());
  };
  window.setLang = (l) => {
    window.LANG = l;
    try { localStorage.setItem("lang", l); } catch (e) {}
    const u = new URL(location.href); u.searchParams.set("lang", l); history.replaceState(null, "", u);
    applyLang();
  };
})();
